const { contextBridge, ipcRenderer } = require('electron')
contextBridge.exposeInMainWorld('mca', {
  start: (secs) => ipcRenderer.invoke('start', secs),
  stop: () => ipcRenderer.invoke('stop'),
  status: () => ipcRenderer.invoke('status'),
  installHelper: () => ipcRenderer.invoke('install-helper'),
  isPro: () => ipcRenderer.invoke('is-pro'),
  version: () => ipcRenderer.invoke('version'),
  upgrade: () => ipcRenderer.invoke('upgrade'),
  activateLicense: (key) => ipcRenderer.invoke('activate-license', key),
  setBatteryProtect: (enabled) => ipcRenderer.invoke('set-battery-protect', enabled),
  setForceSleep: (enabled) => ipcRenderer.invoke('set-force-sleep', enabled),
  setBatteryGrace: (enabled) => ipcRenderer.invoke('set-battery-grace', enabled),
  setRestoreWindow: (enabled) => ipcRenderer.invoke('set-restore-window', enabled),
  nuclearReady: () => ipcRenderer.invoke('nuclear-ready'),
  ensureNuclearSudo: () => ipcRenderer.invoke('ensure-nuclear-sudo'),
  nuclear: (mode) => ipcRenderer.invoke('nuclear', mode),
  getCleanupSuggestions: () => ipcRenderer.invoke('get-cleanup-suggestions'),
  openPath: (p) => ipcRenderer.invoke('open-path', p),
  memList: () => ipcRenderer.invoke('mem-list'),
  memFreeze: (name) => ipcRenderer.invoke('mem-freeze', name),
  memThaw: (name) => ipcRenderer.invoke('mem-thaw', name),
  memThawAll: () => ipcRenderer.invoke('mem-thaw-all'),
  memPurge: () => ipcRenderer.invoke('mem-purge'),
  onTick: (fn) => ipcRenderer.on('tick', (_, n) => fn(n)),
  onRestored: (fn) => ipcRenderer.on('restored', () => fn()),
  onHelperNeeded: (fn) => ipcRenderer.on('helper-needed', () => fn()),
  onProStatus: (fn) => ipcRenderer.on('pro-status', (_, p) => fn(p)),
  onLowPowerStatus: (fn) => ipcRenderer.on('low-power-status', (_, p) => fn(p)),
  onMemRefresh: (fn) => ipcRenderer.on('mem-refresh', () => fn()),
  onCleanupItem: (fn) => ipcRenderer.on('cleanup-item', (_, item) => fn(item)),
})
